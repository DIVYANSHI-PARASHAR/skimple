/* Run against `npm start`. Requires Playwright Chromium; no application dependencies. */
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const { chromium } = require('playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:4173';
const output = process.env.SCREENSHOT_DIR || path.join(__dirname, '..', 'test-results');
fs.mkdirSync(output, { recursive: true });
const tinyPNG = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVQIHWP4z8DwHwAFgAI/ScLbtAAAAABJRU5ErkJggg==', 'base64');
const fixture = {name:'photo.png',mimeType:'image/png',buffer:tinyPNG};

(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  const requests=[];
  page.on('request', request=>requests.push({url:request.url(),method:request.method()}));
  const click = selector => page.locator(selector).click();
  const close = async()=>{await click('.close-button');await page.waitForFunction(()=>!document.querySelector('dialog').open);};
  const text = selector => page.locator(selector).innerText();
  try {
    await page.goto(base);
    await page.evaluate(()=>document.fonts.ready);
    assert.equal(await page.locator('.product-card').count(),6);
    await page.screenshot({path:path.join(output,'home-desktop.png'),fullPage:true});
    await click('[data-filter="Serums"]');
    assert.equal(await page.locator('.product-card').count(),2);
    await page.locator('#product-search').fill('not a real product');
    assert.match(await text('.empty-state'),/No shelf mates/);
    await page.locator('#product-search').fill('');
    await click('[data-filter="All products"]');
    await click('.save-button[data-id="byoma"]');
    await page.reload();
    assert.equal(await page.locator('.save-button[data-id="byoma"]').getAttribute('aria-pressed'),'true');
    console.log('PASS shelf filters, search, favorites, persistence');

    await click('a[href="#product/byoma"]');
    await page.waitForSelector('.detail-hero');
    assert.match(await text('h1'),/Moisturizing Gel-Cream/);
    await click('[data-tab="ingredients"]');
    assert.equal(await page.locator('.ingredient-row').count(),3);
    await click('[data-ingredient="ceramides"]');
    assert.match(await text('dialog'),/not a published paper/);
    await close();
    await click('[data-tab="reviews"]');
    assert.match(await text('#report-content'),/fictional review observations/);
    await click('[data-tab="sources"]');
    assert.equal(await page.locator('.source-card').count(),3);
    await click('[data-tab="overview"]');
    await page.screenshot({path:path.join(output,'product-desktop.png'),fullPage:true});
    console.log('PASS product routing, all report sections, evidence dialogs');

    await click('[data-action="chat"]');
    assert.equal(await page.locator('.chat-monster').count(),1);
    await page.screenshot({path:path.join(output,'chat-desktop.png')});
    await click('.chat-monster');
    await click('button[type="submit"]');
    assert.match(await text('#profile-error'),/skin feel/);
    await page.locator('input[name="feel"][value="Combination"] + span').click();
    await page.locator('input[name="goals"][value="Hydration"] + span').click();
    await page.locator('input[name="sensitivities"][value="Fragrance"] + span').click();
    await page.locator('input[name="routine"][value="Sunscreen"] + span').click();
    await click('button[type="submit"]');
    assert.equal(await page.locator('.chat-monster').count(),0);
    await click('[data-question="Would this suit my skin?"]');
    await page.waitForFunction(()=>document.querySelectorAll('.message-source').length===1);
    assert.match(await text('#messages'),/Combination skin tendencies/);
    assert.match(await text('#messages'),/hydration/i);
    await page.locator('#chat-input').fill('What about my specific question?');
    await click('.send-button');
    await page.waitForFunction(()=>document.querySelectorAll('.message-source').length===2);
    assert.match(await text('#messages'),/For “What about my specific question\?”/);
    await close();
    await page.reload();
    assert.match(await text('.personal-summary'),/Combination/);
    console.log('PASS context monster, questionnaire validation, contextual chat, profile persistence');

    await page.goto(base);
    await click('[data-action="scan"]');
    assert.equal(await page.locator('[data-action="extract"]').isDisabled(),true);
    await page.locator('[data-upload="front"]').setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from('not an image')});
    assert.match(await text('#toast'),/JPG, PNG, or WebP/);
    await page.locator('[data-upload="front"]').setInputFiles(fixture);
    const photoURL=await page.locator('.upload-zone img').getAttribute('src');
    assert.ok(photoURL.startsWith('blob:'));
    await click('[data-action="scan-customize"]');
    await page.locator('[data-upload="face"]').setInputFiles(fixture);
    const faceURL=await page.locator('.face-preview').getAttribute('src');
    assert.equal(await page.locator('#face-form .primary').isEnabled(),true);
    await page.locator('input[name="consent"]').check();
    await click('#face-form .primary');
    await page.waitForSelector('.saved-profile strong');
    assert.match(await text('.saved-profile'),/Face photo discarded/);
    const photoRevoked=await page.evaluate(async url=>{try {await fetch(url);return false;}catch{return true;}},faceURL);
    assert.equal(photoRevoked,true);
    const stored=await page.evaluate(()=>localStorage.getItem('skimple.profile'));
    assert.ok(!stored.includes('blob:')&&!stored.includes('data:image')&&!stored.includes('photo.png'));
    await click('[data-action="return"]');
    assert.equal(await page.locator('[data-action="scan-customize"]').count(),0);
    assert.equal(await page.locator('.upload-zone img').first().getAttribute('src'),photoURL);
    await click('[data-action="extract"]');
    await page.waitForSelector('#confirm-product');
    await page.locator('#product-brand').fill('My little brand');
    await page.locator('#product-name').fill('Happy Skin Cream');
    await click('#confirm-product button[type="submit"]');
    await page.waitForURL(/#product\/demo-/, {timeout:10000});
    await page.waitForFunction(()=>document.querySelector('h1')?.textContent==='Happy Skin Cream');
    assert.equal(await text('h1'),'Happy Skin Cream');
    assert.match(await text('.personal-summary'),/Combination/);
    await page.reload();
    assert.equal(await text('h1'),'Happy Skin Cream');
    console.log('PASS real upload previews, face consent, image disposal, text-only storage, full scan-to-report');

    const reportURL=page.url();
    await click('.profile-button');
    await page.waitForSelector('.skin-sidebar');
    await click('[data-action="forget-profile"]');
    assert.equal(await page.evaluate(()=>localStorage.getItem('skimple.profile')),null);
    await page.goto(reportURL);
    await click('[data-action="chat"]');
    assert.equal(await page.locator('.chat-monster').count(),1);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('dialog').evaluate(d=>d.open),false);
    await page.goto(base);
    await click('[data-action="scan"]');
    await click('[data-action="product-camera"]');
    await page.waitForSelector('.camera-error');
    assert.match(await text('.camera-error'),/uploading|upload a photo/);
    await click('[data-action="scan-back"]');
    await click('[data-action="demo-product"]');
    await click('[data-action="extract"]');
    await close();
    await page.waitForTimeout(1200);
    assert.equal(await page.locator('dialog').evaluate(d=>d.open),false);
    console.log('PASS profile reset, Escape dismissal, camera fallback, cancelled async work');

    for(const width of [390,768,1024,1440]) {
      await page.setViewportSize({width,height:844});
      await page.goto(base);
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`home overflow at ${width}`);
      if(width===390)await page.screenshot({path:path.join(output,'home-mobile.png'),fullPage:true});
      await click('a[href="#product/ordinary"]');
      await page.waitForSelector('.detail-hero');
      assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),`product overflow at ${width}`);
      await click('[data-action="chat"]');
      assert.ok(await page.locator('dialog').evaluate(d=>d.scrollWidth<=d.clientWidth),`dialog overflow at ${width}`);
      if(width===390)await page.screenshot({path:path.join(output,'chat-mobile.png')});
      await page.keyboard.press('Tab');
      assert.ok(await page.evaluate(()=>document.querySelector('dialog').contains(document.activeElement)));
      await close();
    }
    assert.deepEqual(errors,[]);
    assert.equal(requests.filter(r=>r.method!=='GET').length,0);
    console.log('PASS responsive layouts (390–1440), dialog keyboard focus, zero runtime errors, no API writes');
  } finally {await browser.close();}

  const cameraBrowser=await chromium.launch({headless:true,args:['--use-fake-device-for-media-stream','--use-fake-ui-for-media-stream']});
  try {
    const cameraContext=await cameraBrowser.newContext({permissions:['camera'],reducedMotion:'reduce'});
    const cameraPage=await cameraContext.newPage();
    await cameraPage.goto(base);
    await cameraPage.locator('[data-action="scan"]').click();
    await cameraPage.locator('[data-action="product-camera"]').click();
    await cameraPage.waitForFunction(()=>!document.querySelector('#capture-button').disabled);
    await cameraPage.evaluate(()=>window.testStream=document.querySelector('video').srcObject);
    await cameraPage.locator('#capture-button').click();
    await cameraPage.waitForSelector('.upload-zone img');
    assert.equal(await cameraPage.evaluate(()=>window.testStream.getTracks().every(t=>t.readyState==='ended')),true);
    await cameraPage.locator('[data-action="close"]').click();
    console.log('PASS camera capture with virtual device and stopped media tracks');
  } finally {await cameraBrowser.close();}
  console.log(`All journey checks passed. Screenshots: ${output}`);
})().catch(error=>{console.error(error);process.exitCode=1;});
