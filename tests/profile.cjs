const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const {chromium} = require('playwright');
const base = process.env.BASE_URL || 'http://127.0.0.1:4173';
const output = process.env.SCREENSHOT_DIR || path.join(__dirname, '..', 'test-results');
fs.mkdirSync(output, {recursive:true});

(async () => {
  const browser = await chromium.launch({headless:true});
  const context = await browser.newContext({viewport:{width:1440,height:1000},reducedMotion:'reduce'});
  const page = await context.newPage();
  const errors = [], serviceRequests = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => {if(request.method() !== 'GET')serviceRequests.push(request.url());});
  const click = selector => page.locator(selector).click();
  const text = selector => page.locator(selector).innerText();
  const close = async () => {await click('.close-button');await page.waitForFunction(() => !document.querySelector('dialog').open);};
  const choose = (form, name, value) => click(`${form} input[name="${name}"][value="${value}"] + span`);
  const add = async (query, id, keyboard = false) => {
    await click('.add-product-tile');
    await page.locator('#owned-search').fill(query);
    if(keyboard){await page.locator('#owned-search').press('ArrowDown');await page.locator('#owned-search').press('Enter');}
    else await click(`.lookup-option[data-id="${id}"]`);
    await page.waitForFunction(() => !document.querySelector('dialog').open);
  };
  try {
    await page.goto(base);
    await click('.save-button[data-id="byoma"]');
    await click('.profile-button');
    await page.waitForSelector('#skin-page-form');
    assert.match(page.url(),/#skin$/);
    assert.equal(await page.locator('dialog').evaluate(d => d.open),false);
    assert.equal(await page.locator('.skin-section').count(),0);
    assert.equal(await page.locator('.page-questionnaire .question').count(),4);
    await page.evaluate(() => document.fonts.ready);
    await page.screenshot({path:path.join(output,'profile-first-visit.png'),fullPage:true});
    await click('#skin-page-form button[type="submit"]');
    assert.match(await text('#page-profile-error'),/skin feel/);
    await choose('#skin-page-form','feel','Combination');
    await choose('#skin-page-form','goals','Hydration');
    await choose('#skin-page-form','goals','Barrier support');
    await choose('#skin-page-form','sensitivities','Fragrance');
    await choose('#skin-page-form','sensitivities','Strong actives');
    await choose('#skin-page-form','sensitivities','Nothing I know of');
    await click('#skin-page-form button[type="submit"]');
    assert.match(await text('#page-profile-error'),/so your profile is clear/);
    await choose('#skin-page-form','sensitivities','Nothing I know of');
    await page.locator('#page-extra-context').fill('I prefer lightweight textures and a quick routine.');
    await click('#skin-page-form button[type="submit"]');
    await page.waitForSelector('#my-products');
    assert.equal(await page.locator('.skin-section').count(),3);
    assert.equal(await page.locator('.owned-product').count(),0);
    assert.match(await text('.skin-extra-note'),/lightweight textures/);
    assert.match(await text('#my-products'),/waiting for you/);
    assert.equal(await page.locator('.watchout-row').count(),2);
    console.log('PASS first-visit inline questions, validation, extra context, three-section unlock, bookmarks excluded');

    await add('CeraVe','cerave',true);
    assert.equal(await page.locator('.owned-product').count(),1);
    await add('BYOMA','byoma');
    await add('Joseon','joseon');
    await add('Niacinamide 10%','ordinary');
    assert.equal(await page.locator('.owned-product').count(),4);
    assert.equal(await page.locator('.routine-panel.morning .routine-product').count(),3);
    assert.equal(await page.locator('.routine-panel.evening .routine-product').count(),3);
    assert.match(await text('.routine-panel.morning'),/Hydrating Facial Cleanser/);
    assert.match(await text('.routine-panel.morning'),/Relief Sun/);
    assert.match(await text('.routine-panel.evening'),/Niacinamide 10%/);
    assert.equal(await page.locator('.watchout-products a[href="#product/ordinary"]').count(),1);
    await click('.add-product-tile');
    await page.locator('#owned-search').fill('BYOMA');
    assert.equal(await page.locator('.lookup-option[data-id="byoma"]').getAttribute('aria-disabled'),'true');
    await page.locator('.lookup-option[data-id="byoma"]').click({force:true});
    assert.equal(await page.locator('.owned-product').count(),4);
    await page.locator('#owned-search').fill('an unknown product');
    assert.match(await text('.lookup-empty'),/No little match/);
    await page.locator('#owned-search').fill('<img src=x onerror=alert(1)>');
    assert.equal(await page.locator('.lookup-options img').count(),0);
    await close();
    await page.reload();
    assert.equal(await page.locator('.owned-product').count(),4);
    await page.screenshot({path:path.join(output,'profile-desktop.png'),fullPage:true});
    console.log('PASS simulated search, keyboard selection, duplicate prevention, persistence, owned-product routines and watch-out matches');

    await click('.skin-sidebar [data-action="update-skin"]');
    assert.equal(await page.locator('#extra-context').inputValue(),'I prefer lightweight textures and a quick routine.');
    await page.locator('#extra-context').fill('A cancelled edit.');
    await close();
    assert.match(await text('.skin-extra-note'),/lightweight textures/);
    await click('.skin-sidebar [data-action="update-skin"]');
    await choose('#skin-form','sensitivities','Fragrance');
    await page.locator('#extra-context').fill('I like a soft finish. <b>My words stay text.</b>');
    await click('#skin-form button[type="submit"]');
    await page.waitForFunction(() => !document.querySelector('dialog').open);
    assert.equal(await page.locator('.watchout-row').count(),1);
    assert.equal(await page.locator('.skin-extra-note b').count(),0);
    assert.match(await text('.skin-extra-note'),/<b>My words stay text.<\/b>/);
    await click('.owned-product .save-button[data-id="byoma"]');
    assert.equal(await page.locator('.owned-product').count(),4);
    await click('[data-action="remove-owned"][data-id="byoma"]');
    assert.equal(await page.locator('.owned-product').count(),3);
    assert.equal(await page.locator('.routine-panel.morning .routine-product').count(),2);
    assert.equal(await page.locator('.routine-panel.morning .routine-add').count(),1);
    await click('.routine-panel.morning .routine-add');
    assert.equal(await page.locator('#owned-search').inputValue(),'Moisturizers');
    assert.equal(await page.locator('.lookup-option').count(),2);
    await close();
    await click('.owned-product a[href="#product/ordinary"]');
    await page.waitForSelector('.detail-owned');
    assert.match(await text('.detail-owned'),/In my products/);
    await click('[data-action="chat"]');
    await click('[data-question="What do the ingredients do?"]');
    await page.waitForSelector('.message-source');
    assert.match(await text('#messages'),/I like a soft finish/);
    assert.equal(await page.locator('#messages b').count(),0);
    await close();
    await click('.detail-owned');
    assert.match(await text('.detail-owned'),/I use this product/);
    await click('.detail-owned');
    assert.match(await text('.detail-owned'),/In my products/);
    console.log('PASS profile edits/cancellation, safe free-text rendering and chat context, removal, routine gaps, product-page ownership');

    for(const width of [320,390,768,1024,1440]) {
      await page.setViewportSize({width,height:844});
      await page.goto(`${base}/#skin`);
      assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth),`profile overflow at ${width}`);
      if(width === 390) await page.screenshot({path:path.join(output,'profile-mobile.png'),fullPage:true});
      await click('.add-product-tile');
      assert.ok(await page.locator('dialog').evaluate(d => d.scrollWidth <= d.clientWidth),`lookup overflow at ${width}`);
      if(width === 390)await page.screenshot({path:path.join(output,'profile-search-mobile.png')});
      await close();
    }
    await click('[data-action="forget-profile"]');
    await page.waitForSelector('#skin-page-form');
    assert.equal(await page.evaluate(() => localStorage.getItem('skimple.profile')),null);
    assert.equal(await page.locator('.skin-section').count(),0);
    assert.equal(JSON.parse(await page.evaluate(() => localStorage.getItem('skimple.owned'))).length,3);
    await page.setViewportSize({width:390,height:844});
    await page.screenshot({path:path.join(output,'profile-first-visit-mobile.png'),fullPage:true});
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
    await choose('#skin-page-form','feel','Dry & tight');
    await choose('#skin-page-form','goals','Barrier support');
    await page.locator('#page-extra-context').fill('My extra context survives a temporary photo.');
    await click('#skin-page-form [data-action="face"]');
    await click('[data-action="demo-face"]');
    await page.locator('input[name="consent"]').check();
    await click('#face-form .primary');
    await page.waitForSelector('.saved-profile strong');
    assert.equal(JSON.parse(await page.evaluate(() => localStorage.getItem('skimple.profile'))).feel.length,0);
    await click('[data-action="return"]');
    await page.waitForFunction(() => !document.querySelector('dialog').open);
    assert.equal(await page.locator('#skin-page-form input[value="Dry & tight"]').isChecked(),true);
    assert.equal(await page.locator('#page-extra-context').inputValue(),'My extra context survives a temporary photo.');
    await click('#skin-page-form button[type="submit"]');
    assert.equal(await page.locator('.skin-section').count(),3);
    assert.equal(await page.locator('.skin-photo-note').count(),1);
    assert.deepEqual(errors,[]);
    assert.deepEqual(serviceRequests,[]);
    console.log('PASS responsive skin page (320–1440), local profile reset, retained owned products, zero runtime errors or API writes');
    console.log('PASS inline questionnaire-to-photo round trip, preserved drafts, photo-only onboarding gate');
  } finally {await browser.close();}
  console.log('All personal skin-space checks passed.');
})().catch(error => {console.error(error);process.exitCode=1;});
